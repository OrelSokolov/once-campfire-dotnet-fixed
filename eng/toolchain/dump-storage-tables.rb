# Dumps the lookup tables Campfire.Application.Storage ports verbatim from the reference gems,
# as C#:
#
# * Marcel's extension, type-extension, parent and magic tables (after
#   marcel/mime_type/definitions.rb has extended them), which drive Active Storage's content type
#   identification (Marcel::MimeType.for).
# * I18n's default transliteration approximations, which ActionDispatch::Http::ContentDisposition
#   uses for the ASCII `filename=` parameter.
#
# It is the C# twin of reference-tools/storage/dump_tables.rb (which writes Rust). Run it with the
# reference image's bundle, so the gem versions are the ones Gemfile.lock resolves:
#
#   podman run --rm -v "$PWD/eng/toolchain:/tools:ro" localhost/campfire-reference:app \
#     bundle exec ruby /tools/dump-storage-tables.rb \
#     > src/Campfire.Application/Storage/Marcel/StorageTables.g.cs
require "marcel"
require "i18n"

# A byte string as lowercase hex: no C# escaping pitfalls (`\x` takes up to four digits).
def hex(string) = "\"#{string.b.unpack1("H*")}\""

# A C# string literal. Every value in these tables is ASCII; anything else is escaped as UTF-16.
def str(string)
  escaped = string.each_char.map do |char|
    case char
    when "\"" then "\\\""
    when "\\" then "\\\\"
    when " ".."~" then char
    else char.encode("UTF-16BE").unpack("n*").map { format("\\u%04x", _1) }.join
    end
  end
  "\"#{escaped.join}\""
end

def matches(list)
  "[" + list.map { |offset, value, children|
    range_begin, range_end = offset.is_a?(Range) ? [ offset.begin, offset.end.to_s ] : [ offset, "null" ]
    value_code = value ? hex(value) : "null"
    children_code = children ? matches(children) : "[]"
    "new( #{range_begin}, #{range_end}, #{value_code}, #{children_code} )"
  }.join(", ") + "]"
end

puts "// <auto-generated>"
puts "// Generated by eng/toolchain/dump-storage-tables.rb from marcel #{Marcel::VERSION} and i18n #{I18n::VERSION}"
puts "// (the reference image's bundle). Do not edit by hand; regenerate instead."
puts "// </auto-generated>"
puts
puts "namespace Campfire.Application.Storage.Marcel;"
puts
puts "internal static class MarcelTables"
puts "{"
puts "    /// <summary><c>Marcel::EXTENSIONS</c>: extension => type.</summary>"
puts "    internal static readonly (string Extension, string Type)[] Extensions ="
puts "    ["
Marcel::EXTENSIONS.sort.each { |ext, type| puts "        ( #{str(ext)}, #{str(type)} )," }
puts "    ];"
puts
puts "    /// <summary><c>Marcel::TYPE_EXTS</c>: type => extensions, in table order (<c>extensions.first</c> matters).</summary>"
puts "    internal static readonly (string Type, string[] Extensions)[] TypeExtensions ="
puts "    ["
Marcel::TYPE_EXTS.sort.each { |type, exts| puts "        ( #{str(type)}, [#{exts.map { str(_1) }.join(", ")}] )," }
puts "    ];"
puts
puts "    /// <summary><c>Marcel::TYPE_PARENTS</c>: type => parent types.</summary>"
puts "    internal static readonly (string Type, string[] Parents)[] TypeParents ="
puts "    ["
Marcel::TYPE_PARENTS.sort.each { |type, parents| puts "        ( #{str(type)}, [#{parents.map { str(_1) }.join(", ")}] )," }
puts "    ];"
puts
puts "    /// <summary>"
puts "    /// <c>Marcel::MAGIC</c>, in lookup order (the first matching entry wins). Each match is"
puts "    /// <c>[offset, value, children]</c>, where the offset may be a range; values are hex bytes."
puts "    /// </summary>"
puts "    internal static readonly (string Type, MagicMatch[] Matches)[] Magic ="
puts "    ["
Marcel::MAGIC.each { |type, list| puts "        ( #{str(type)}, #{matches(list)} )," }
puts "    ];"
puts "}"
puts
puts "internal static class I18nApproximations"
puts "{"
puts "    /// <summary><c>I18n::Backend::Transliterator::HashTransliterator::DEFAULT_APPROXIMATIONS</c>, by code point.</summary>"
puts "    internal static readonly (int CodePoint, string Ascii)[] Default ="
puts "    ["
I18n::Backend::Transliterator::HashTransliterator::DEFAULT_APPROXIMATIONS.sort.each do |char, ascii|
  raise "expected a single character: #{char.inspect}" unless char.length == 1
  puts "        ( 0x#{char.ord.to_s(16).rjust(4, "0")}, #{str(ascii)} ), // #{char}"
end
puts "    ];"
puts "}"
