# Generates src/Campfire.Web/Presenters/AllEmoji.g.cs: the code points Campfire's String#all_emoji?
# (reference/lib/rails_ext/string.rb) accepts, taken from Ruby's own regexp engine so they match
# Onigmo's Unicode tables exactly. Run with the reference image's Ruby (3.4.x, Unicode 15.0):
#
#   ruby eng/generators/all-emoji-ranges.rb src/Campfire.Web/Presenters/AllEmoji.g.cs
re = /\A(\p{Emoji_Presentation}|\p{Extended_Pictographic}|️)\z/u
ranges = []
start = nil
prev = nil
(0..0x10FFFF).each do |cp|
  next if (0xD800..0xDFFF).cover?(cp)
  next unless [cp].pack("U").match?(re)

  if start && prev == cp - 1
    prev = cp
  else
    ranges << [start, prev] if start
    start = cp
    prev = cp
  end
end
ranges << [start, prev] if start

rows = ranges.map { |a, b| format("        (0x%X, 0x%X),", a, b) }.join("\n")
File.write(ARGV.fetch(0), <<~CS)
  // <auto-generated>
  // eng/generators/all-emoji-ranges.rb with Ruby #{RUBY_VERSION} (Unicode #{RbConfig::CONFIG["UNICODE_VERSION"]}).
  // </auto-generated>

  namespace Campfire.Web.Presenters;

  public static partial class AllEmoji
  {
      /// <summary>
      /// The code points of <c>\\p{Emoji_Presentation}|\\p{Extended_Pictographic}|\\uFE0F</c>, as inclusive ranges in
      /// ascending order.
      /// </summary>
      private static readonly (int First, int Last)[] Ranges =
      [
  #{rows}
      ];
  }
CS
puts "#{ranges.size} ranges, Unicode #{RbConfig::CONFIG["UNICODE_VERSION"]}, Ruby #{RUBY_VERSION}"
