    private const int MaximumIdentifierBytes = 4096;

    private static void RequireSyntheticMarker( SqliteConnection db )
    {
        using var command = db.CreateCommand( );
        command.CommandText = "SELECT value FROM ar_internal_metadata WHERE key = @marker";
        command.Parameters.AddWithValue( "@marker", MarkerKey );
        if ( command.ExecuteScalar( ) as string != "1" )
        {
            throw new InvalidOperationException( "The database is not marked as a synthetic fixture. Refusing credential conversion." );
        }
    }

    private static string? DecodeFixtureString( string? encoded )
    {
        if ( encoded is null )
        {
            return null;
        }

        var bytes = Base64Url.DecodeFromChars( encoded.TrimEnd( '=' ).Replace( '+', '-' ).Replace( '/', '_' ) );
        var offset = 2;
        if ( bytes.Length < 4 || bytes.Length > MaximumIdentifierBytes || bytes[0] != 4 || bytes[1] != 8 )
        {
            throw new InvalidDataException( "Invalid synthetic string envelope." );
        }

        var hasEncoding = bytes[offset] == ( byte ) 'I';
        if ( hasEncoding )
        {
            offset++;
        }

        if ( bytes.Length - offset < 2 )
        {
            throw new InvalidDataException( "Truncated fixture string header." );
        }

        if ( bytes[offset++] != ( byte ) '"' )
        {
            throw new InvalidDataException( "Only a serialized string is supported in a fixture identifier." );
        }

        var size = bytes[offset++];
        var length = size > 4 ? size - 5 : 0;
        if ( size is > 0 and <= 4 )
        {
            if ( bytes.Length - offset < size )
            {
                throw new InvalidDataException( "Truncated fixture string length." );
            }

            for ( var index = 0; index < size; index++ )
            {
                length |= bytes[offset++] << (index * 8);
            }
        }

        var suffix = hasEncoding ? new byte[] { 6, ( byte ) ':', 6, ( byte ) 'E', ( byte ) 'T' } : [];
        if ( length < 0 || length > bytes.Length - offset || !bytes.AsSpan( offset + length ).SequenceEqual( suffix ) )
        {
            throw new InvalidDataException( "Unsupported fixture string encoding." );
        }

        return new UTF8Encoding( false, true ).GetString( bytes, offset, length );
    }

