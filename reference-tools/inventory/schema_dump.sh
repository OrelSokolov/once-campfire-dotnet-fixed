#!/usr/bin/env bash
# Dumps the schema the reference creates on an empty database (plan M0 step 5): `bin/rails
# db:prepare` in the reference image, in production mode, on an empty storage directory, then the
# image's sqlite3 CLI prints `.schema` and the rows of schema_migrations and ar_internal_metadata.
#
#   PATH="$PWD/eng/docker-shim:$PATH" reference-tools/inventory/schema_dump.sh
#
# Writes schema-dump.sql, and compares the database's sqlite_master (minus what
# SQLite derives itself: sqlite_sequence, autoindexes and the FTS5 shadow tables, as Rust's
# crates/db/src/schema.rs describes vectors/db/schema.sql) with vectors/db/schema.sql into
# schema-vector-check.txt.
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
OUT=$ROOT/docs/inventory
STORAGE=$(mktemp -d)
trap 'rm -rf "$STORAGE"' EXIT

"$ROOT/parity/bin/reference" exec --storage "$STORAGE" -- bash -c '
  set -euo pipefail
  bin/rails db:prepare > /dev/null
  db=storage/db/production.sqlite3
  echo "-- The schema the reference creates on an empty database: bin/rails db:prepare (production,"
  echo "-- Rails $(bin/rails runner "print Rails.version"), SQLite $(bundle exec ruby -e "require %q(sqlite3); print SQLite3::SQLITE_VERSION") in the sqlite3 gem), dumped with the image'"'"'s sqlite3 CLI $(sqlite3 --version | cut -d" " -f1)."
  echo "-- Generated by reference-tools/inventory/schema_dump.sh. ar_internal_metadata timestamps are the dump time."
  echo
  echo "-- .schema"
  sqlite3 "$db" .schema
  echo
  echo "-- schema_migrations"
  sqlite3 "$db" ".mode insert schema_migrations" "SELECT * FROM schema_migrations ORDER BY version"
  echo
  echo "-- ar_internal_metadata"
  sqlite3 "$db" ".mode insert ar_internal_metadata" "SELECT * FROM ar_internal_metadata ORDER BY key"
  echo
  echo "-- sqlite_master (type, name, tbl_name) in creation order"
  sqlite3 "$db" "SELECT \"-- \" || type || \" \" || name || \" on \" || tbl_name FROM sqlite_master ORDER BY rowid"
' > "$OUT/schema-dump.sql"

"$ROOT/parity/bin/reference" exec --storage "$STORAGE" -- bash -c '
  sqlite3 storage/db/production.sqlite3 "SELECT sql || \";\" FROM sqlite_master
    WHERE sql IS NOT NULL AND name <> \"sqlite_sequence\"
      AND name NOT IN (\"message_search_index_data\", \"message_search_index_idx\", \"message_search_index_docsize\", \"message_search_index_config\", \"message_search_index_content\")
    ORDER BY rowid"
' > "$STORAGE/sqlite_master.sql"

{
  echo "# sqlite_master of a fresh db:prepare (derived objects removed) vs vectors/db/schema.sql"
  if cmp -s "$STORAGE/sqlite_master.sql" "$ROOT/vectors/db/schema.sql"; then
    echo "identical ($(wc -l < "$ROOT/vectors/db/schema.sql") lines, sha256 $(sha256sum < "$ROOT/vectors/db/schema.sql" | cut -c1-64))"
  else
    diff -u "$ROOT/vectors/db/schema.sql" "$STORAGE/sqlite_master.sql" || true
  fi
} > "$OUT/schema-vector-check.txt"
cat "$OUT/schema-vector-check.txt" >&2
